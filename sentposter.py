def get_image_url(page_number: int) -> str:
    page_str = str(page_number).zfill(3)
    return f"https://surahquran.com/img/pages-quran/page{page_str}.png"

async def send_adhkar(app):
    while True:
        post = random.choice(ADHKAR)
        await app.bot.send_message(chat_id=CHANNEL_ID, text=post)
        await asyncio.sleep(1800)  

current_page = 1 

async def send_quran_page(app):

    global current_page
    if current_page > 604:  
        current_page = 1

    img_url = get_image_url(current_page)
    await app.bot.send_photo(chat_id=CHANNEL_ID, photo=img_url, caption=f"صفحة {current_page}")
    print(f"✅ Sent Quran page {current_page}")
    current_page += 1


# ================== BOT ==================
async def start(update, context):
    await update.message.reply_text("✅ تم تفعيل البوت. سيرسل الأذكار كل نصف ساعة وصورة من المصحف يوميًا 10 مساءً.")

async def post_init(app):
    # Start adhkar loop
    asyncio.create_task(send_adhkar(app))

    # Daily Quran page at 10 PM
    scheduler = AsyncIOScheduler(timezone="Africa/Algiers")
    # Pass the function reference and pass arguments using 'args'
    scheduler.add_job(send_quran_page, "cron", hour=00, minute=11, args=[app])
    scheduler.start()


def main():
    app = Application.builder().token(BOT_TOKEN).post_init(post_init).build()
    app.add_handler(CommandHandler("start", start))
    app.run_polling()


if __name__ == "__main__":
    main()